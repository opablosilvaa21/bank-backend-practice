-- Transactional Outbox: o evento é gravado aqui NA MESMA transação da transferência.
-- Um relay lê os pendentes (published_at IS NULL), publica no Kafka e marca como publicados.
CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ID da mensagem: vai no payload e no cabeçalho do Kafka; é a chave de deduplicação do consumidor.
    event_id       UUID                     NOT NULL,
    aggregate_type VARCHAR(50)              NOT NULL,
    aggregate_id   VARCHAR(100)             NOT NULL,
    event_type     VARCHAR(100)             NOT NULL,
    topic          VARCHAR(100)             NOT NULL,
    message_key    VARCHAR(100)             NOT NULL,
    payload        JSONB                    NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at   TIMESTAMP(6) WITH TIME ZONE,
    -- Tentativas que falharam (Kafka fora do ar, por exemplo) e o último erro, para diagnóstico.
    attempts       INT                      NOT NULL DEFAULT 0,
    last_error     VARCHAR(500),
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id)
);

-- Índice parcial: só os pendentes, que é o que o relay procura. Os publicados não pesam na busca.
CREATE INDEX ix_outbox_events_pending ON outbox_events (id) WHERE published_at IS NULL;
CREATE INDEX ix_outbox_events_aggregate ON outbox_events (aggregate_type, aggregate_id);
