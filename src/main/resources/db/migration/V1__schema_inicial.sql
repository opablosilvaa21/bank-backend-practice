-- Schema inicial do DevBank. Uma migration aplicada nunca é editada: mudanças entram em um novo arquivo V2, V3...

CREATE TABLE customers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(255)             NOT NULL,
    cpf        VARCHAR(11)              NOT NULL,
    email      VARCHAR(255)             NOT NULL,
    birth_date DATE                     NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_customers_cpf UNIQUE (cpf),
    CONSTRAINT uk_customers_email UNIQUE (email)
);

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT                   NOT NULL,
    agency         VARCHAR(4)               NOT NULL,
    account_number VARCHAR(12)              NOT NULL,
    type           VARCHAR(20)              NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    balance        NUMERIC(19, 2)           NOT NULL,
    opened_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT uk_accounts_agency_number UNIQUE (agency, account_number),
    CONSTRAINT ck_accounts_type CHECK (type IN ('CORRENTE', 'POUPANCA')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),
    -- Última barreira: mesmo com um bug no Java, o banco recusa saldo negativo.
    CONSTRAINT ck_accounts_balance CHECK (balance >= 0)
);

-- O PostgreSQL não indexa chaves estrangeiras sozinho.
CREATE INDEX ix_accounts_customer ON accounts (customer_id);

CREATE TABLE account_transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT                   NOT NULL,
    type          VARCHAR(30)              NOT NULL,
    amount        NUMERIC(19, 2)           NOT NULL,
    balance_after NUMERIC(19, 2)           NOT NULL,
    description   VARCHAR(140)             NOT NULL,
    transfer_id   UUID,
    occurred_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_account_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT ck_account_transactions_type CHECK (type IN ('DEPOSITO', 'SAQUE', 'PAGAMENTO', 'TRANSFERENCIA_ENVIADA',
        'TRANSFERENCIA_RECEBIDA', 'PIX_ENVIADO', 'PIX_RECEBIDO', 'RENDIMENTO')),
    CONSTRAINT ck_account_transactions_amount CHECK (amount > 0)
);

-- Extrato: filtra por conta e ordena por data.
CREATE INDEX ix_account_transactions_account_occurred ON account_transactions (account_id, occurred_at);
CREATE INDEX ix_account_transactions_transfer ON account_transactions (transfer_id);

CREATE TABLE pix_keys (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_type   VARCHAR(20)              NOT NULL,
    key_value  VARCHAR(77)              NOT NULL,
    account_id BIGINT                   NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_pix_keys_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT uk_pix_keys_value UNIQUE (key_value),
    CONSTRAINT ck_pix_keys_type CHECK (key_type IN ('CPF', 'EMAIL', 'ALEATORIA'))
);

CREATE INDEX ix_pix_keys_account ON pix_keys (account_id);
