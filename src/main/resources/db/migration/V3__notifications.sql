-- Avisos para o cliente ("Você recebeu R$ 50,00 de Ana Costa por Pix"), criados a partir do evento de transferência.
-- Sem chave estrangeira para transfers: quem cria as notificações só conhece o evento, não a tabela de outro módulo.
CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT                   NOT NULL,
    transfer_id UUID                     NOT NULL,
    message     VARCHAR(200)             NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    -- Cada transferência gera no máximo um aviso por conta, mesmo se o evento chegar duas vezes.
    CONSTRAINT uk_notifications_transfer_account UNIQUE (transfer_id, account_id)
);

CREATE INDEX ix_notifications_account_created ON notifications (account_id, created_at);
